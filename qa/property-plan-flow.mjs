import { chromium } from 'playwright';
import { mkdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const out = fileURLToPath(new URL('../tmp/property-plan-qa/', import.meta.url));
await mkdir(out, { recursive: true });
const executablePath = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH
  || (process.platform === 'win32' ? 'C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe' : undefined);
const browser = await chromium.launch({ headless: true, executablePath });
try {
  const page = await browser.newPage({ viewport: { width: 1365, height: 900 }, acceptDownloads: true });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.BASE_URL || 'http://127.0.0.1:5173/');
  await page.getByRole('button', { name: '04 Property Schedules' }).click();
  await page.getByRole('button', { name: '+ Add another property' }).click();
  await page.getByRole('button', { name: '11 Property Plan' }).click();
  assert.equal(await page.getByRole('button', { name: /^Schedule / }).count(), 2);
  await page.getByRole('button', { name: /^Schedule 1/ }).click();
  await page.getByRole('button', { name: 'Open library' }).click();
  await page.getByRole('button', { name: 'Sample templates' }).click();
  await page.getByRole('button', { name: 'Load', exact: true }).first().click();
  assert.equal(await page.getByRole('spinbutton', { name: 'Area (Sq. Yards)' }).inputValue(), '572');
  await page.getByRole('button', { name: 'Save / update plan' }).click();
  await page.getByRole('button', { name: 'Saved plans' }).click();
  assert.equal(await page.getByRole('button', { name: 'Duplicate' }).count(), 1);
  await page.getByRole('button', { name: 'Save as new copy' }).click();
  await page.getByRole('button', { name: 'Duplicate' }).nth(1).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Duplicate' }).count(), 2);
  const backupDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export all backup' }).click();
  await (await backupDownload).saveAs(out + 'plans-backup.json');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete' }).first().click();
  await page.waitForFunction(() => [...document.querySelectorAll('button')].filter(button => button.textContent?.trim() === 'Duplicate').length === 1);
  assert.equal(await page.getByRole('button', { name: 'Duplicate' }).count(), 1);
  await page.locator('input[type=file][accept=".json,application/json"]').setInputFiles(out + 'plans-backup.json');
  await page.getByRole('button', { name: 'Duplicate' }).nth(1).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Duplicate' }).count(), 2);
  await page.getByRole('button', { name: /Review plan changes for deed/ }).click();
  await page.getByRole('checkbox', { name: /Survey no\./ }).check();
  await page.getByRole('button', { name: 'Apply selected fields to deed' }).click();
  await page.getByRole('button', { name: '04 Property Schedules' }).click();
  await page.getByRole('button', { name: /^Schedule 1/ }).click();
  assert.equal(await page.getByRole('textbox', { name: 'Survey no(s).' }).inputValue(), '508/B');
  await page.getByRole('textbox', { name: 'Survey no(s).' }).fill('508/C');
  await page.getByRole('button', { name: '11 Property Plan' }).click();
  await page.getByRole('button', { name: 'Review re-sync from deed' }).click();
  await page.getByRole('checkbox', { name: /surveyNo/ }).check();
  await page.getByRole('button', { name: 'Apply selected deed facts to plan' }).click();
  assert.equal(await page.getByRole('textbox', { name: 'Survey no(s).' }).inputValue(), '508/C');
  await page.locator('.plan-sketch-canvas').first().scrollIntoViewIfNeeded();
  await page.screenshot({ path: out + 'house.png' });
  await page.getByRole('checkbox', { name: /I checked this plan/ }).check();
  await page.getByRole('button', { name: 'Use this plan in deed' }).click();
  assert(await page.getByText('This plan is selected for this schedule.').isVisible());
  await page.getByRole('button', { name: /^Schedule 2/ }).click();
  assert.equal(await page.getByRole('spinbutton', { name: 'Area (Sq. Yards)' }).inputValue(), '');
  await page.getByRole('button', { name: 'Open library' }).click();
  await page.getByRole('button', { name: 'Sample templates' }).click();
  await page.getByRole('button', { name: 'Load', exact: true }).nth(1).click();
  assert.equal(await page.getByRole('spinbutton', { name: 'Area (Sq. Yards)' }).inputValue(), '272.25');
  await page.locator('.plan-sketch-canvas').first().scrollIntoViewIfNeeded();
  await page.screenshot({ path: out + 'open-place.png' });
  await page.getByRole('button', { name: 'Load', exact: true }).nth(3).click();
  await page.locator('.plan-sketch-canvas text').filter({ hasText: 'CORNER PROPERTY' }).first().waitFor();
  await page.locator('.plan-sketch-canvas').first().scrollIntoViewIfNeeded();
  await page.waitForTimeout(200);
  await page.screenshot({ path: out + 'corner-road.png' });
  await page.getByRole('button', { name: '+ Add another house / shed' }).click();
  await page.getByRole('textbox', { name: 'Structure name' }).first().fill('Main House');
  await page.getByRole('textbox', { name: /House width/ }).first().fill("15'");
  await page.getByRole('textbox', { name: /House length/ }).first().fill("20'");
  await page.getByRole('textbox', { name: 'Structure name' }).nth(1).fill('Shed');
  await page.getByRole('textbox', { name: /House width/ }).nth(1).fill("12'");
  await page.getByRole('textbox', { name: /House length/ }).nth(1).fill("18'");
  assert.equal(await page.locator('#structure-1').first().count(), 1);
  await page.locator('#structure-2').first().waitFor();
  await page.locator('.plan-sketch-canvas').first().scrollIntoViewIfNeeded();
  await page.waitForTimeout(200);
  await page.screenshot({ path: out + 'multi-structure.png' });
  await page.getByRole('button', { name: /^Schedule 1/ }).click();
  assert.equal(await page.getByRole('spinbutton', { name: 'Area (Sq. Yards)' }).inputValue(), '572');
  assert(await page.getByText('This plan is selected for this schedule.').isVisible());
  await page.getByRole('button', { name: '10 Generate Deed' }).click();
  const pdfDownload = page.waitForEvent('download', { timeout: 20000 });
  await page.getByRole('button', { name: 'Download plan PDF' }).click();
  await (await pdfDownload).saveAs(out + 'combined-plan.pdf');
  assert((await readFile(out + 'combined-plan.pdf')).subarray(0, 4).toString() === '%PDF');
  const wordDownload = page.waitForEvent('download', { timeout: 20000 });
  await page.getByRole('button', { name: /Download Word 2007 deed/ }).click();
  await (await wordDownload).saveAs(out + 'deed-with-plan.docx');
  assert((await readFile(out + 'deed-with-plan.docx')).subarray(0, 2).toString() === 'PK');
  assert.deepEqual(errors, []);
  console.log('PASS: schedule plans stay separate; house and open-place previews, combined PDF, and deed DOCX render without browser errors.');
} finally {
  await browser.close();
}

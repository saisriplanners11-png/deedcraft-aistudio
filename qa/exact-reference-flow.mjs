  await page.getByRole('button', { name: 'Review and refresh from deed', exact: true }).click();
  await page.getByRole('checkbox', { name: /property · surveyNo/ }).check();
  await page.getByRole('button', { name: 'Apply selected deed facts to plan', exact: true }).click();
  await expect(frame.locator('#input-survey-no')).toHaveValue('DEED/NEW');
  await frame.getByRole('button', { name: 'Saved (0)', exact: true }).click();
  await frame.getByRole('button', { name: 'Sample Templates (5)', exact: true }).click();
  await expect(frame.getByRole('button', { name: 'Load Template', exact: true })).toHaveCount(5);
  await frame.getByRole('button', { name: 'Load Template', exact: true }).first().click();
  await expect(frame.locator('#input-area-sq-yards')).toHaveValue('572');
  const sliders = frame.locator('#section-boundaries-details input[type=range]');
  await expect(sliders).toHaveCount(3);
  for (const slider of await sliders.all()) {
    assert.equal(await slider.getAttribute('min'), '50'); assert.equal(await slider.getAttribute('max'), '200'); assert.equal(await slider.getAttribute('step'), '5');
  }
  await frame.getByRole('button', { name: '160%', exact: true }).first().click();
  await expect(sliders.first()).toHaveValue('160');
  await page.getByRole('button', { name: 'Use this plan in deed', exact: true }).click();

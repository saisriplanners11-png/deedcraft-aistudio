  await expect(page.frameLocator('iframe[title="Property Plan Generator"]').getByRole('heading', { name: 'PROPERTY PLAN GENERATOR', exact: true })).toBeVisible();
  assert.deepEqual(errors, []);
  console.log('Exact reference flow passed: pre-fill, refresh, presets, schedule isolation, selection invalidation, library, PDF/DOCX exports, saved-deed restore, existing plan steps.');
